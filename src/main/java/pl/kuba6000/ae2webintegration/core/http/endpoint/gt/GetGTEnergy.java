package pl.kuba6000.ae2webintegration.core.http.endpoint.gt;

import java.net.HttpURLConnection;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;

import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import com.github.bsideup.jabel.Desugar;

import pl.kuba6000.ae2webintegration.core.WebPrincipal;
import pl.kuba6000.ae2webintegration.core.api.gt.GTMachineSnapshot;
import pl.kuba6000.ae2webintegration.core.config.Config;
import pl.kuba6000.ae2webintegration.core.gt.GTEnergyLog;
import pl.kuba6000.ae2webintegration.core.gt.GTMachineRegistry;
import pl.kuba6000.ae2webintegration.core.history.HistoryDb;
import pl.kuba6000.ae2webintegration.core.http.ApiStatus;
import pl.kuba6000.ae2webintegration.core.http.ErrorResponse;
import pl.kuba6000.ae2webintegration.core.http.contract.Endpoint;
import pl.kuba6000.ae2webintegration.core.http.contract.HttpMethod;
import pl.kuba6000.ae2webintegration.core.http.contract.OptionalInput;
import pl.kuba6000.ae2webintegration.core.http.contract.QueryParam;

/**
 * EU each visible GregTech machine consumed or generated over a range: where the power goes and which generators
 * carry the base. Sampled from the scans (EU/t times the ticks between them), so it covers loaded machines only.
 * Most consumed first.
 *
 * @response 200 {@link Response} Successful response.
 * @response 400 {@link ErrorResponse} BAD_PARAM: malformed query parameter.
 * @responseExample 400 {"status":"BAD_PARAM","data":null}
 * @response 401 {@link ErrorResponse} UNAUTHORIZED: no valid session was provided.
 * @response 404 {@link ErrorResponse} NOT_AVAILABLE: GregTech is not installed or its pages are disabled.
 *           HISTORY_DISABLED when no history database is configured.
 * @response 500 {@link ErrorResponse} INTERNAL_ERROR: the request could not be completed.
 * @responseExample 401 {"status":"UNAUTHORIZED","data":null}
 * @responseExample 404 {"status":"NOT_AVAILABLE","data":null}
 * @responseExample 500 {"status":"INTERNAL_ERROR","data":null}
 */
@Endpoint(method = HttpMethod.GET, path = "/api/gt/energy")
public final class GetGTEnergy extends GTRequest {

    /**
     * Successful operation result.
     *
     * @param status {@code OK} for a successful request
     * @param data   EU per machine over the range
     * @example status OK
     */
    @Desugar
    public record Response(@NotNull ApiStatus status, @NotNull JSON_GTEnergy data) {}

    /** Time range ending now: 15m, 1h, 6h, 24h, 7d, 30d, 90d, all (the configured retention) or custom. */
    @QueryParam("range")
    @OptionalInput
    private String range = "24h";

    /** Length of a {@code custom} range in minutes. */
    @QueryParam("minutes")
    @OptionalInput
    private @Nullable Integer minutes;

    public static class JSON_GTEnergy {

        /**
         * Range start in Unix epoch milliseconds.
         *
         * @example 1700000000000
         */
        public long from;
        /**
         * Range end in Unix epoch milliseconds.
         *
         * @example 1700086400000
         */
        public long to;
        /**
         * EU consumed by every listed machine together.
         *
         * @example 1728000000000
         */
        public long totalConsumed;
        /**
         * EU generated by every listed machine together.
         *
         * @example 2073600000000
         */
        public long totalGenerated;
        /** Machines with any EU in the range, most consumed first, then most generated. */
        public List<Machine> machines = new ArrayList<>();
    }

    public static class Machine {

        /**
         * Machine id, {@code dim:x:y:z} of the controller.
         *
         * @example 0:100:64:-20
         */
        public String id;
        /**
         * Localized machine name.
         *
         * @example Electric Blast Furnace
         */
        public String name;
        /**
         * Unlocalized machine type, for grouping.
         *
         * @example multimachine.blastfurnace
         */
        public String type;
        /**
         * Owner's player name; null when unknown.
         *
         * @example Steve
         */
        public @Nullable String ownerName;
        /**
         * Voltage tier index (0 = ULV ... 6 = LuV); -1 if unknown.
         *
         * @example 5
         */
        public int voltageTier;
        /**
         * EU consumed in the range.
         *
         * @example 86400000000
         */
        public long consumed;
        /**
         * EU generated in the range.
         *
         * @example 0
         */
        public long generated;
    }

    @Override
    protected void handleGT(WebPrincipal principal) {
        Long span = parseRange(range, minutes, TimeUnit.DAYS.toMillis(Config.INSTANCE.gregtech.stateRetentionDays));
        if (span == null) {
            deny(ApiStatus.BAD_PARAM);
            return;
        }
        if (HistoryDb.get() == null) {
            deny(ApiStatus.HISTORY_DISABLED);
            return;
        }
        long now = System.currentTimeMillis();
        JSON_GTEnergy data = new JSON_GTEnergy();
        data.from = now - span;
        data.to = now;
        for (Map.Entry<String, long[]> entry : GTEnergyLog.totals(data.from, now, visibleTo(principal))
            .entrySet()) {
            GTMachineSnapshot snapshot = GTMachineRegistry.get(entry.getKey());
            if (snapshot == null) continue;
            Machine machine = new Machine();
            machine.id = snapshot.id;
            machine.name = snapshot.name;
            machine.type = snapshot.type;
            machine.ownerName = snapshot.ownerName;
            machine.voltageTier = snapshot.voltageTier;
            machine.consumed = entry.getValue()[0];
            machine.generated = entry.getValue()[1];
            if (machine.consumed == 0 && machine.generated == 0) continue;
            data.totalConsumed = saturatingAdd(data.totalConsumed, machine.consumed);
            data.totalGenerated = saturatingAdd(data.totalGenerated, machine.generated);
            data.machines.add(machine);
        }
        data.machines.sort(
            Comparator.comparingLong((Machine m) -> m.consumed)
                .reversed()
                .thenComparing(
                    Comparator.comparingLong((Machine m) -> m.generated)
                        .reversed())
                .thenComparing(m -> m.id));
        respond(HttpURLConnection.HTTP_OK, new Response(ApiStatus.OK, data));
    }

    private static long saturatingAdd(long a, long b) {
        long sum = a + b;
        return sum < 0 ? Long.MAX_VALUE : sum;
    }
}
